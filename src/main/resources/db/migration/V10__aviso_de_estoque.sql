-- ---------------------------------------------------------------------------
-- Aviso interno de estoque por e-mail, e a regua unica de classificacao.
--
-- Ate aqui o nivel de cada tipo saia de um percentual da capacidade alvo, igual
-- para todos (30% e 60%, em application.yml). A equipe pensa em bolsas, e cada
-- tipo tem a sua folga: a partir daqui cada tipo guarda os seus dois minimos, em
-- bolsas, e painel, convocacao e aviso interno leem a mesma regua.
--
-- Os minimos nascem dos percentuais antigos, arredondados para cima, de modo que
-- nenhum tipo muda de nivel por causa desta migration.
-- ---------------------------------------------------------------------------
ALTER TABLE estoque_hemocomponente ADD COLUMN minimo_critico INTEGER;
ALTER TABLE estoque_hemocomponente ADD COLUMN minimo_baixo INTEGER;
-- Ultimo nivel de que a equipe foi avisada. Vazio enquanto o tipo esta normal. E o que
-- impede o mesmo alerta de sair a cada bolsa retirada, e fica no banco para sobreviver
-- a reinicio do servico.
ALTER TABLE estoque_hemocomponente ADD COLUMN nivel_avisado VARCHAR(20);

UPDATE estoque_hemocomponente SET minimo_critico = (capacidade_alvo * 30 + 99) / 100;
UPDATE estoque_hemocomponente
   SET minimo_baixo = GREATEST((capacidade_alvo * 60 + 99) / 100, minimo_critico + 1);

ALTER TABLE estoque_hemocomponente ALTER COLUMN minimo_critico SET NOT NULL;
ALTER TABLE estoque_hemocomponente ALTER COLUMN minimo_baixo SET NOT NULL;
ALTER TABLE estoque_hemocomponente
    ADD CONSTRAINT ck_estoque_minimos CHECK (minimo_critico > 0 AND minimo_baixo > minimo_critico);

-- Uma linha so, como no disparo automatico: e configuracao do sistema. Nao ha coluna de
-- ligado/desligado de proposito: o aviso e controle interno e ninguem o desliga pela tela.
-- So a hora do relatorio diario se ajusta.
CREATE TABLE aviso_estoque (
    id                   BIGINT        PRIMARY KEY,
    -- Hora cheia, no fuso de Sao Paulo, a partir da qual o relatorio do dia sai
    hora_relatorio       INTEGER       NOT NULL,
    -- Dia do ultimo relatorio: garante um por dia, mesmo com o servico dormindo no horario
    ultimo_relatorio_em  DATE,
    atualizado_por       VARCHAR(180),
    atualizado_em        TIMESTAMP,
    CONSTRAINT ck_aviso_estoque_linha_unica CHECK (id = 1),
    CONSTRAINT ck_aviso_estoque_hora CHECK (hora_relatorio >= 0 AND hora_relatorio <= 23)
);

-- Quem recebe sao os administradores ativos, lidos das contas na hora do envio; nao ha
-- lista propria.
INSERT INTO aviso_estoque (id, hora_relatorio) VALUES (1, 7);

-- Registro de cada aviso enviado, para a tela mostrar o que saiu e quando.
CREATE TABLE aviso_estoque_envio (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(20)  NOT NULL,
    assunto       VARCHAR(200) NOT NULL,
    destinatarios INTEGER      NOT NULL,
    falhas        INTEGER      NOT NULL,
    enviado_em    TIMESTAMP    NOT NULL
);

CREATE INDEX idx_aviso_estoque_envio_quando ON aviso_estoque_envio (enviado_em DESC);
